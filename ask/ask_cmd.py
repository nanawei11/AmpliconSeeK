    args.output_pdat_1    = str(ask_paths["output_pdat_1"])
    args.output_pdat_2    = str(ask_paths["output_pdat_2"])
    args.output_pdat_3    = str(ask_paths["output_pdat_3"])
    args.output_pdat_4    = str(ask_paths["output_pdat_4"])

    return args


